/** Column masks, compiled once. Bit `y` of a column is the pixel at row `y`. */
function compile(glyphs: Record<string, string[]>): Record<string, number[]> {
  const out: Record<string, number[]> = {};
  for (const [char, rows] of Object.entries(glyphs)) {
    const width = rows[0].length;
    const columns: number[] = [];
    for (let x = 0; x < width; x += 1) {
      let mask = 0;
      for (let y = 0; y < rows.length; y += 1) {
        if (rows[y][x] === "1") mask |= 1 << y;
      }
      columns.push(mask);
    }
    out[char] = columns;
  }
  return out;
}

const COMPILED = { small: compile(SMALL), large: compile(LARGE) };

export type FontName = "small" | "large";

/** A space is one blank column: the firmware's own, measured. */
const SPACE = [0];

/** What an unknown character draws. The display has no "missing glyph" box —
 *  it draws a question mark — so the preview does the same. */
function fallback(font: FontName): number[] {
  return COMPILED[font]["?"] ?? SPACE;
}

/** One blank column between glyphs, as the firmware spaces them. */
export const LETTER_SPACING = 1;

export function rasterize(text: string, font: FontName = "small"): number[] {
  const columns: number[] = [];
  for (const char of text) {
    if (columns.length) columns.push(0); // one blank column between glyphs
    if (char === " ") {
      columns.push(...SPACE);
      continue;
    }
    columns.push(...(COMPILED[font][char] ?? fallback(font)));
  }
  return columns;
}

export function textWidth(text: string, font: FontName = "small"): number {
  return rasterize(text, font).length;
}

export function heightFor(font: FontName): number {
  return font === "large" ? GLYPH_HEIGHT_LARGE : GLYPH_HEIGHT;
}
